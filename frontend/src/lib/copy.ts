export function getCopy(): any {
  try {
    const locale = localStorage.getItem("v2.lang");
    if (locale === "en") return copyEn;
  } catch {
    // ignore
  }
  return copyVi;
}

export function translateVi(value: string) {
  const direct = VI_TO_EN.get(value);
  if (direct !== undefined) return direct;
  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(value)) return value.replace(pattern, replacement);
  }
  return value;
}

/**
 * Translate static UI text in the current document for the English locale.
 * It only replaces exact text-node / attribute matches so logs, code blocks,
 * and dynamic values are left untouched.
 */
export function translateDocument(root: Document | Element = document) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (node) => {
      const parent = node.parentElement;
      if (!parent) return NodeFilter.FILTER_SKIP;
      const tag = parent.tagName;
      if (/^(SCRIPT|STYLE|NOSCRIPT|PRE|CODE|TEXTAREA)$/i.test(tag)) return NodeFilter.FILTER_REJECT;
      const value = (node as Text).data.trim();
      return value && translateVi(value) !== value ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_SKIP;
    },
  });
  let node: Node | null;
  while ((node = walker.nextNode())) {
    if (node.nodeType === Node.TEXT_NODE) {
      const textNode = node as Text;
      const text = textNode.data;
      const trimmed = text.trim();
      const translated = translateVi(trimmed);
      if (translated !== trimmed) {
        textNode.data = text.replace(trimmed, translated);
      }
    }
  }

  const translatedAttrs = new Set(["placeholder", "aria-label", "title", "alt"]);
  for (const element of root.querySelectorAll<HTMLElement>("[placeholder],[aria-label],[title],[alt]")) {
    for (const attr of translatedAttrs) {
      const value = element.getAttribute(attr);
      const translated = value ? translateVi(value) : null;
      if (translated && translated !== value) element.setAttribute(attr, translated);
    }
  }
}

const copyProxy = new Proxy({}, {
  get(_target, key: string) {
    return (getCopy() as Record<string, unknown>)[key];
  },
});

